#!/usr/bin/env python3
"""Write a direct-coupling sweep configuration for simulate_coupled_sweep.jl.

Reads a base TOML (simulation, hidden, gene rates, coupling_defaults and
[sweep] folds) and adds one scheme per model:
  - gene1 -> gene2 one-way, for every rate set and source state
  - gene2 -> gene1 one-way, likewise
  - reciprocal: every pairing of a gene1 -> gene2 and a gene2 -> gene1 choice
  - one uncoupled control (fold fixed at 1)

    python3 make_direct_sweep.py direct_base.toml direct_CCAT1_MYC_sweep.toml
"""
import argparse, itertools, json, tomllib

RATE_SETS = ["R12", "R21", "R23", "R32", "Initiate",
             "R12+R23", "R21+R32", "R12+R23+Initiate", "R21+R32+Initiate"]


def toml_value(v):
    if isinstance(v, bool):
        return str(v).lower()
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    raise TypeError(f"unsupported TOML value {v!r}")


def table(name, values, array=False):
    head = f"[[{name}]]" if array else f"[{name}]"
    return "\n".join([head] + [f"{k} = {toml_value(v)}" for k, v in values.items()])


def block(scheme, source, state, target, rates, mode, fold=None):
    b = dict(scheme=scheme, source=source, source_state=state, target=target,
             rates=rates.split("+"), mode=mode)
    if fold is not None:
        b["fold"] = fold
    return b


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("base")
    p.add_argument("out")
    p.add_argument("--rate-sets", nargs="+", default=RATE_SETS, help="rates joined by +")
    p.add_argument("--source-states", nargs="+", type=int, default=[3],
                   help="promoter states of the source gene that regulate (default: 3)")
    p.add_argument("--mode", choices=["activate", "inhibit"], default="activate")
    p.add_argument("--no-one-way", action="store_true", help="only reciprocal schemes and the control")
    a = p.parse_args()

    config = tomllib.loads(open(a.base).read())
    if "coupling" in config or "coupling_scheme" in config.get("sweep", {}):
        raise SystemExit("the base file must not define [[coupling]] blocks or sweep.coupling_scheme")
    choices = [(s, r) for s in a.source_states for r in a.rate_sets]
    schemes, blocks = ["uncoupled"], [block("uncoupled", "gene1", 3, "gene2", "R12", a.mode, fold=1.0)]
    if not a.no_one_way:
        for s, r in choices:
            name = f"CCAT1_s{s}_{r}__to_MYC"
            schemes.append(name); blocks.append(block(name, "gene1", s, "gene2", r, a.mode))
        for s, r in choices:
            name = f"MYC_s{s}_{r}__to_CCAT1"
            schemes.append(name); blocks.append(block(name, "gene2", s, "gene1", r, a.mode))
    for (s, r), (t, q) in itertools.product(choices, repeat=2):
        name = f"reciprocal__CCAT1_s{s}_{r}__MYC_s{t}_{q}"
        schemes.append(name)
        blocks.append(block(name, "gene1", s, "gene2", r, a.mode))
        blocks.append(block(name, "gene2", t, "gene1", q, a.mode))

    config.setdefault("sweep", {})["coupling_scheme"] = schemes
    parts = [f"# Generated by make_direct_sweep.py from {a.base}; edit the base file and regenerate."]
    for name, values in config.items():
        if isinstance(values, dict):
            parts.append(table(name, values))
    parts += [table("coupling", b, array=True) for b in blocks]
    open(a.out, "w").write("\n\n".join(parts) + "\n")
    folds = len(config["sweep"].get("coupling_fold", [1]))
    nsim = config.get("simulation", {}).get("nsim", "?")
    print(f"{len(schemes)} schemes ({len(choices)**2} reciprocal) x {folds} folds = "
          f"{len(schemes) * folds} scenarios, {nsim} simulations each -> {a.out}")


if __name__ == "__main__":
    main()
